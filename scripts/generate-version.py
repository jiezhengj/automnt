#!/usr/bin/env python3
"""Derive build metadata exclusively from the root Swift entry."""
import argparse
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = (root / 'automnt.swift').read_text()
matches = re.findall(r'^let automntVersion = "(\d+\.\d+\.\d+)"$', source, re.M)
if len(matches) != 1:
    raise SystemExit('Expected exactly one root marketing-version declaration')
version = matches[0]
for directory in ('Sources', 'apps'):
    for path in (root / directory).rglob('*.swift'):
        if re.search(r'\blet automntVersion\s*=', path.read_text()):
            raise SystemExit(f'Duplicate version declaration: {path.relative_to(root)}')
major, minor, patch = map(int, version.split('.'))
outputs = {
    root / 'Sources/AutomntCore/BuildVersion.swift':
        f'// Generated by scripts/generate-version.py; do not edit.\npublic enum AutomntBuildVersion {{\n    public static let value = "{version}"\n}}\n',
    root / 'apps/Automnt/Resources/Version.xcconfig':
        f'// Generated; marketing version derives from automnt.swift.\nMARKETING_VERSION = {version}\nCURRENT_PROJECT_VERSION = {major * 1000000 + minor * 1000 + patch}\n'
}
for path, text in outputs.items():
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit(f'Stale version metadata: {path.relative_to(root)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
info = (root / 'apps/Automnt/Resources/Info.plist').read_text()
for key, token in [('CFBundleShortVersionString', 'MARKETING_VERSION'), ('CFBundleVersion', 'CURRENT_PROJECT_VERSION')]:
    if not re.search(r'<key>' + key + r'</key>\s*<string>\$\(' + token + r'\)</string>', info):
        raise SystemExit(f'Info.plist must derive {key} from {token}')
print(version)
